export function pickRandomSplashQuote(): SplashQuote {
  return splashQuotes[Math.floor(Math.random() * splashQuotes.length)];
}

const SESSION_KEY = "tj:splashQuote";

/**
 * One quote per app session — picked once at boot (splash screen) and reused
 * on the dashboard banner so both show the same line.
 */
export function getSessionSplashQuote(): SplashQuote {
  try {
    const raw = sessionStorage.getItem(SESSION_KEY);
    if (raw) return JSON.parse(raw) as SplashQuote;
  } catch {
    // sessionStorage unavailable — fall through to a fresh pick.
  }
  const quote = pickRandomSplashQuote();
  try {
    sessionStorage.setItem(SESSION_KEY, JSON.stringify(quote));
  } catch {
    // Ignore storage errors (e.g. private browsing).
  }
  return quote;
}
